-- Save and report unified Product / Job / Real Estate listings.
create table if not exists public.saved_listings (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  listing_type text not null check (listing_type in ('product','job','real_estate')),
  listing_id text not null,
  created_at timestamptz not null default now(),
  unique(user_id, listing_type, listing_id)
);
create index if not exists saved_listings_user_created_idx on public.saved_listings(user_id, created_at desc);

create table if not exists public.listing_reports (
  id bigint generated by default as identity primary key,
  reporter_id uuid not null references auth.users(id) on delete cascade,
  listing_type text not null check (listing_type in ('product','job','real_estate')),
  listing_id text not null,
  reason text not null check (char_length(reason) between 3 and 1000),
  status text not null default 'pending' check (status in ('pending','reviewed','dismissed','actioned')),
  created_at timestamptz not null default now(),
  unique(reporter_id, listing_type, listing_id)
);
create index if not exists listing_reports_status_created_idx on public.listing_reports(status, created_at desc);

alter table public.saved_listings enable row level security;
alter table public.listing_reports enable row level security;
